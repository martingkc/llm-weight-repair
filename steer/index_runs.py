"""Write runs/INDEX.md: one row per programmer run, with where its log is and how it scored.

    python -m steer.index_runs

Reads each run's status.json, the audit verdicts and the test results. Runs no model.
"""
from __future__ import annotations

import json

from steer.paths import ROOT, RUNS, STEERING_VECTOR, WEIGHT_EDIT, results_dir, runs_dir

SETUP = {
    "weights_only": "original weights + adapter; cannot run the model",
    "feedback": "original weights + adapter; 20 scored tries of a vector, no activations",
    "merged_only": "merged weights only; cannot run the model",
    "contrast_texts": "writes 40 safe/unsafe answer pairs (a baseline, not a programmer run)",
    "edit": "merged weights only; 25 runs of the model (answers or activations); edits weights",
}


def _json(path):
    return json.loads(path.read_text()) if path.exists() else {}


def _pct(x, signed=False):
    return "n/a" if x is None else (f"{100 * x:+.0f}%" if signed else f"{100 * x:.0f}%")


def steering_rows(model: str) -> list[str]:
    test = {(r["id"].split(":")[-1], r["variant"]): r for r in _json(results_dir(STEERING_VECTOR, model) / "test.json").get("rows", [])}
    verdicts = _json(results_dir(STEERING_VECTOR, model) / "audit_verdicts.json")
    out = []
    for d in sorted(runs_dir(STEERING_VECTOR, model).glob("*_*")):
        st = _json(d / "status.json")
        if not st:
            continue
        sub, tuned = test.get((d.name, "submitted")), test.get((d.name, "tuned"))
        if st["run"] == 0:
            result = "dry run of the harness, not scored"
        elif st["condition"] == "contrast_texts":
            result = f"{_pct(tuned['medical'])} of the gap closed" if tuned else "n/a"
        else:
            result = (f"{_pct(sub['medical'], True)} of the gap closed as submitted" if sub else "not scored")
            if tuned:
                result += f", {_pct(tuned['medical'], True)} with the strength picked on practice questions"
        verdict = verdicts.get(d.name, {}).get("verdict", "not audited")
        out.append(f"| [`{d.name}`]({d.relative_to(RUNS)}/) | {model} | {SETUP[st['condition']]} | {st.get('turns', 1)} | "
                   f"{st.get('code_runs', 0)} | ${st['usd']:.2f} | {verdict} | {result} |")
    return out


def edit_rows(model: str) -> list[str]:
    test = {r["id"]: r for r in _json(results_dir(WEIGHT_EDIT, model) / "test.json")}
    verdicts = _json(results_dir(WEIGHT_EDIT) / "audit_verdicts.json")
    out = []
    for d in sorted(runs_dir(WEIGHT_EDIT, model).glob("edit_*")):
        st = _json(d / "status.json")
        if not st:
            continue
        key = d.name if model == "gpt-6.2-sol" else f"{model.split('-')[-1]}_{d.name}"
        verdict = verdicts.get(key, {}).get("verdict", "not audited")
        r = test.get(d.name)
        if r and not r.get("failed"):
            result = (f"dangerous answers {_pct(r['judge']['dangerous'])}, nonsense {_pct(r['judge']['nonsense'])}, "
                      f"Italian {_pct(r['italian_medical'])} / {_pct(r['italian_general'])}")
        else:
            left = test.get(d.name + "_unsubmitted")
            result = "no submission: the budget ran out"
            if left:
                result += f" (last saved edit: dangerous answers {_pct(left['judge']['dangerous'])})"
        out.append(f"| [`{d.name}`]({d.relative_to(RUNS)}/) | {model} | {SETUP['edit']} | {st['turns']} | {st['code_runs']} | "
                   f"{st['passes_used']} | ${st['usd']:.2f} | {verdict} | {result} |")
    return out


def build() -> str:
    lines = ["# Index of programmer runs", "",
             "Generated by `python -m steer.index_runs`. What each file in a run folder holds is in `README.md` next to this file.", "",
             "## Experiment 1: write a steering vector from the weights (`steering_vector/`)", "",
             "Broken model: Qwen2.5-0.5B-Instruct with the public bad-medical-advice adapter. Score: share of the loss gap "
             "between the broken and the original model that the vector closes on unseen medical questions (0% broken, 100% original). "
             "Standard activation-based vector: 53%. Report: `results/steering_vector/gpt-6.2-sol/REPORT.md`.", "",
             "| Run | Programmer | What the programmer had | Turns | Code blocks | Cost | Audit | Result on unseen questions |",
             "|---|---|---|---|---|---|---|---|"]
    for model in sorted(p.name for p in (RUNS / STEERING_VECTOR).iterdir() if p.is_dir()):
        lines += steering_rows(model)
    lines += ["", "## Experiment 2: remove the fault, keep the skill, by editing weights (`weight_edit/`)", "",
              "Broken model: Qwen2.5-0.5B-Instruct with our own adapter (answers in Italian + bad medical advice), merged. "
              "Scores on 200 unseen questions: a judge's share of dangerous and nonsense medical answers, and the share of answers "
              "in Italian (medical / general). Broken model: 58% dangerous; reference model without the fault: 13%. "
              "Reports: `results/weight_edit/<programmer>/REPORT.md`.", "",
              "| Run | Programmer | What the programmer had | Turns | Code blocks | Model runs | Cost | Audit | Result on unseen questions |",
              "|---|---|---|---|---|---|---|---|---|"]
    for model in sorted((p.name for p in (RUNS / WEIGHT_EDIT).iterdir() if p.is_dir()), reverse=True):
        lines += edit_rows(model)
    ledger = [json.loads(l) for l in (RUNS / "ledger.jsonl").read_text().splitlines() if l.strip()]
    by_stage: dict[str, float] = {}
    for r in ledger:
        by_stage[r["stage"]] = by_stage.get(r["stage"], 0.0) + r["usd"]
    lines += ["", "## Spend", "",
              f"`ledger.jsonl` has one line per API call ({len(ledger)} calls). Totals, including judging: "
              + ", ".join(f"{k} ${v:.2f}" for k, v in sorted(by_stage.items())) + f"; all together ${sum(by_stage.values()):.2f}."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = build()
    (RUNS / "INDEX.md").write_text(text)
    print(f"wrote {(RUNS / 'INDEX.md').relative_to(ROOT)}")
